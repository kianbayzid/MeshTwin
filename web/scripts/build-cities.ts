// Rebuilds src/map/cities.ts, the console's "MeshCore cities" jump list (docs/data-sources.md, Console city list).
// One-off, by hand; the console never fetches either source.
//   1. Save https://analyzer.letsmesh.net/ from a browser (the region picker is in the page: "SEA - Seattle, US" + a count).
//   2. Download https://davidmegginson.github.io/ourairports-data/airports.csv (public domain).
//   3. node --experimental-strip-types scripts/build-cities.ts <analyzer.html> <airports.csv> [min-count] > src/map/cities.ts
import { readFileSync, statSync } from 'node:fs';

const [html, csv, min = '4'] = process.argv.slice(2);
if (!html || !csv) throw new Error('usage: build-cities.ts <analyzer.html> <airports.csv> [min-count]');

// City codes with no airport of their own: a public city-centre point.
const NO_AIRPORT: Record<string, [number, number, string]> = { NYC: [-74.006, 40.713, 'NY'] };

const unescape = (s: string) => s.replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"');
const regions = [...readFileSync(html, 'utf8').matchAll(
  /class="region-name">([A-Z0-9]{3}) - ([^<]*), US<\/span>(?:<!---->)?<span[^>]*badge[^>]*>(\d+)<\/span>/g,
)].map(([, code, name, count]) => ({ code: code!, name: unescape(name!), count: Number(count) }));
if (regions.length === 0) throw new Error(`no "XXX - City, US" regions found in ${html}`);

// RFC 4180 fields: quoted fields may hold commas and "" escapes (OurAirports has no newlines inside fields).
const fields = (line: string) => [...line.matchAll(/(?:^|,)("(?:[^"]|"")*"|[^,]*)/g)].map((m) => m[1]!.replace(/^"|"$/g, '').replace(/""/g, '"'));
const [header, ...lines] = readFileSync(csv, 'utf8').split(/\r?\n/).filter(Boolean);
const col = Object.fromEntries(fields(header!).map((h, i) => [h, i]));
const airports = new Map<string, [number, number, string]>(); // lon, lat, state
for (const l of lines) {
  const f = fields(l);
  if (f[col.iso_country!] !== 'US' || !f[col.iata_code!] || !/_airport$/.test(f[col.type!]!)) continue;
  airports.set(f[col.iata_code!]!, [Number(f[col.longitude_deg!]), Number(f[col.latitude_deg!]), f[col.iso_region!]!.slice(3)]);
}

const r3 = (x: number) => Math.round(x * 1000) / 1000;
const out = regions
  .filter((r) => r.count >= Number(min))
  .map((r) => {
    const at = NO_AIRPORT[r.code] ?? airports.get(r.code);
    if (!at) throw new Error(`${r.code} (${r.name}): no US airport with this IATA code; add it to NO_AIRPORT`);
    return { ...r, state: at[2], lon: r3(at[0]), lat: r3(at[1]) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

console.log(`// Generated by scripts/build-cities.ts from the LetsMesh analyzer region list (snapshot ${statSync(html).mtime.toLocaleDateString('en-CA')},
// US regions with a count of ${min}+) and OurAirports coordinates. Camera targets only: no nodes. Do not edit by hand.
export interface City {
  code: string; // IATA code, as LetsMesh observers and MeshTwin regions use it
  name: string;
  state: string; // two-letter, from the airport's region
  count: number; // the analyzer's badge for the region (observers, UNVERIFIED)
  lon: number;
  lat: number;
}

export const CITIES: City[] = [
${out.map((c) => `  ${JSON.stringify(c)},`).join('\n')}
];`);
