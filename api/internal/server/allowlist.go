// withMeta adds the meta envelope every summary carries.
func withMeta(paths map[string]string) map[string]string {
	maps.Copy(paths, map[string]string{
		"meta":                "object",
		"meta.schema_version": "number",
		"meta.region":         "string",
		"meta.generated_at":   "time",
		"meta.window":         "object",
		"meta.window.from":    "time",
		"meta.window.to":      "time",
		"meta.source":         "string",
	})
	return paths
}
